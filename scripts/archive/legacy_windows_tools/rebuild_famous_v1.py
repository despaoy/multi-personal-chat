def write(recs, path, version, system, id_prefix):
    samples = []
    for (turns, scene, imp, sfile, sl, el, sid, inters, sgrp, note, adapt) in recs:
        seq = int(sid.split("_")[-1])
        sid_full = f"kisaki_game_{id_prefix}_{seq:04d}"
        messages = [{"role": "system", "content": system}]
        for user, assistant in turns:
            messages.append({"role": "user", "content": user})
            messages.append({"role": "assistant", "content": assistant})
        md = {
            "character": "月社妃",
            "source": "game_extract",
            "scene": scene,
            "importance": imp,
            "prompt_adaptation": "contextualized",
            "assistant_adaptation": adapt,
            "source_file": sfile,
            "start_line": sl,
            "end_line": el,
            "source_scene_id": sid,
            "assistant_speaker": "妃",
            "interlocutors": inters,
            "split_group": sgrp,
            "turns": len(turns),
            "note": note,
            "version": version,
        }
        samples.append({"messages": messages, "id": sid_full, "metadata": md})
    with path.open("w", encoding="utf-8") as f:
        for s in samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")
    n_assistant = sum(len(s["messages"]) // 2 for s in samples)
    chars = sum(len(m["content"]) for s in samples for m in s["messages"] if m["role"] == "assistant")
    print(f"{path.name}: {len(samples)} 条, {n_assistant} assistant回合, {chars} 字符")
    return samples


