def build_single_turn_samples() -> list[dict]:
    """构建单轮对话样本。"""
    samples = []
    for idx, (prompt, response, scene) in enumerate(SINGLE_TURN, 1):
        sample_id = f"kisaki_llm_v4_{idx:04d}"
        sample = {
            "conversations": [
                {"from": "human", "value": prompt},
                {"from": "assistant", "value": response},
            ],
            "id": sample_id,
            "metadata": {
                "character": "月社妃",
                "data_source": "llm_v4_manual",
                "scene": scene,
                "source": "manual_generated_v4",
                "turns": 1,
                "version": "v4_manual",
            },
            "system": SYSTEM_PROMPT,
        }
        samples.append(sample)
    return samples


def build_multi_turn_samples(offset: int) -> list[dict]:
    """构建多轮对话样本。"""
    samples = []
    for idx, (turns, scene) in enumerate(MULTI_TURN, 1):
        sample_id = f"kisaki_llm_v4_{offset + idx:04d}"
        conversations = []
        for i, text in enumerate(turns):
            role = "human" if i % 2 == 0 else "assistant"
            conversations.append({"from": role, "value": text})
        sample = {
            "conversations": conversations,
            "id": sample_id,
            "metadata": {
                "character": "月社妃",
                "data_source": "llm_v4_manual",
                "scene": scene,
                "source": "manual_generated_v4",
                "turns": len(turns) // 2,
                "version": "v4_manual",
            },
            "system": SYSTEM_PROMPT,
        }
        samples.append(sample)
    return samples


def build_daily_prompts(samples: list[dict]) -> dict:
    """构建日常题目集。"""
    prompts = []
    for s in samples:
        convs = s["conversations"]
        prompt = convs[0]["value"] if convs else ""
        prompts.append({
            "id": s["id"],
            "category": s["metadata"]["scene"],
            "prompt": prompt,
            "turns": s["metadata"]["turns"],
            "source": "v4_manual",
        })

    # 按类别统计
    from collections import Counter
    cat_counts = Counter(p["category"] for p in prompts)

    return {
        "version": "v1",
        "total": len(prompts),
        "category_counts": dict(cat_counts),
        "design_principles": [
            "口语化，像真实QQ聊天",
            "避免文学化、情境化表述",
            "避免禁令式、元叙事式提问",
            "覆盖日常、情感、请求、安全等多场景",
        ],
        "prompts": prompts,
    }


def main() -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # 构建所有样本
    single_samples = build_single_turn_samples()
    multi_samples = build_multi_turn_samples(len(single_samples))
    all_samples = single_samples + multi_samples

    # 输出候选样本 JSONL
    with open(CANDIDATES_OUTPUT, "w", encoding="utf-8") as f:
        for s in all_samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    # 输出日常题目集 JSON
    prompts_data = build_daily_prompts(all_samples)
    PROMPTS_OUTPUT.write_text(
        json.dumps(prompts_data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    # 统计
    from collections import Counter
    scene_counts = Counter(s["metadata"]["scene"] for s in all_samples)
    turn_counts = Counter(s["metadata"]["turns"] for s in all_samples)

    print(f"=== V4 候选样本生成完成 ===")
    print(f"总样本数: {len(all_samples)}")
    print(f"  单轮: {len(single_samples)}")
    print(f"  多轮: {len(multi_samples)}")
    print(f"\n按场景分布:")
    for scene, count in sorted(scene_counts.items()):
        print(f"  {scene}: {count}")
    print(f"\n按轮数分布:")
    for turns, count in sorted(turn_counts.items()):
        print(f"  {turns}轮: {count}")
    print(f"\n输出文件:")
    print(f"  候选样本: {CANDIDATES_OUTPUT}")
    print(f"  题目集: {PROMPTS_OUTPUT}")

    # 质量检查
    print(f"\n=== 质量检查 ===")
    issues = []
    for s in all_samples:
        for conv in s["conversations"]:
            text = conv["value"]
            if conv["from"] != "assistant":
                continue
            # 检查AI自称（仅assistant）
            for kw in ["我是AI", "作为AI", "语言模型", "AI助手"]:
                if kw in text:
                    issues.append(f"{s['id']}: AI自称 '{kw}'")
            # 检查元叙事（仅assistant）
            for kw in ["故事里", "作者", "正因如此"]:
                if kw in text:
                    issues.append(f"{s['id']}: 元叙事 '{kw}'")
            # 检查回复长度
            if len(text) > 80:
                issues.append(f"{s['id']}: 回复过长 ({len(text)}字符)")
            if len(text) < 3:
                issues.append(f"{s['id']}: 回复过短 ({len(text)}字符)")

    if issues:
        print(f"发现 {len(issues)} 个问题:")
        for issue in issues[:20]:
            print(f"  {issue}")
    else:
        print("所有样本通过质量检查 ✓")

    return 0


